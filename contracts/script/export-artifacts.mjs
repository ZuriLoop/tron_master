// Writes the tron-solc ABIs into the SDK and the factory deploy artifact into
// the CLI as generated TypeScript. Run after `compile-tron.mjs`.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(ROOT, "out-tron");
const read = (name) => JSON.parse(readFileSync(join(OUT, `${name}.json`), "utf8"));
const header = "// GENERATED by contracts/script/export-artifacts.mjs — do not edit.\n";

const abis = ["PaymasterFactory", "PermitAccount", "DepositForwarder"].map((n) => {
  const a = read(n);
  return `export const ${n[0].toLowerCase()}${n.slice(1)}Abi = ${JSON.stringify(a.abi, null, 2)} as const;\n`;
});
writeFileSync(join(ROOT, "..", "sdk", "src", "abi.ts"), `${header}\n${abis.join("\n")}`);

const factory = read("PaymasterFactory");
writeFileSync(
  join(ROOT, "..", "cli", "src", "artifacts.ts"),
  `${header}
export const paymasterFactoryArtifact = {
  compiler: ${JSON.stringify(factory.compiler)},
  bytecode: ${JSON.stringify(factory.bytecode)},
} as const;
`,
);
console.log("exported sdk/src/abi.ts and cli/src/artifacts.ts");
